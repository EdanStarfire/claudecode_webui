def _long_history(path: Path, n=300):
    records = []
    for i in range(n):
        records.append({"type": "user", "message_id": f"u{i}", "content": f"needle number {i}"})
        records.append({"type": "assistant", "message_id": f"a{i}", "content": f"reply {i} no match here",
                        "metadata": {"tool_uses": []}})
    return _write(path, records)


def test_pages_tile_without_loss_or_duplicates(tmp_path):
    reader = _long_history(tmp_path / "messages.jsonl")
    caps = SearchCaps(max_results=50, max_scan_bytes=10**12, max_wall_s=600)
    results, pages = search_all(reader, "needle", caps)
    assert [r["message_id"] for r in results] == [f"u{i}" for i in reversed(range(300))]
    # the 6th page ends exactly on the cap, so a final empty page reports exhaustion
    assert len(pages) == 7 and all(len(p.results) == 50 for p in pages[:6]) and not pages[-1].results
    assert pages[0].stopped_by == "results" and not pages[0].exhausted
    assert pages[-1].exhausted and pages[-1].next_cursor is None
    assert 0 < pages[0].scanned_fraction < 1
    # each result carries its record's cursor / size_hint (usable as an around= target)
    first = results[0]
    assert first["cursor"].startswith("b:") and first["type"] == "user"
    assert first["size_hint"] == int(first["cursor"][2:])


def test_byte_cap_continues_and_scanned_bytes_are_bounded(tmp_path):
    reader = _long_history(tmp_path / "messages.jsonl", n=2000)
