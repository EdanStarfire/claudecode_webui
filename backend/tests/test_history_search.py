def _tool_history(path: Path, filler: int = 0):
    records = [
        {"type": "user", "message_id": "u1", "content": "go"},
        {"type": "assistant", "message_id": "a1", "content": "calling", "metadata": {"tool_uses": [{"id": "toolu_A"}]}},
    ]
    for i in range(filler):
        records.append({"type": "assistant", "message_id": f"f{i}", "content": "x" * 200, "metadata": {}})
    records += [
        {"type": "tool_call", "message_id": "tc1", "tool_use_id": "toolu_A", "name": "Bash",
         "input": {"command": "needle in input"}, "status": "pending"},
        {"type": "tool_call", "message_id": "tc2", "tool_use_id": "toolu_A", "name": "Bash",
         "input": {"command": "needle in input"}, "status": "completed",
         "result": "needle in result"},
        {"type": "user", "message_id": "u2", "content": "needle later"},
    ]
    return _write(path, records)


def test_tool_hits_attributed_to_parent_once_newest_record_wins(tmp_path):
    results, _ = search_all(_tool_history(tmp_path / "m.jsonl"), "needle")
    assert [(r["message_id"], r["field"], r["occurrence_index"]) for r in results] == [
        ("u2", "content", 0), ("a1", "tool_input", 0), ("a1", "tool_result", 1),
    ]
    assert results[1]["tool_id"] == "toolu_A"
    # a tool hit's cursor/size_hint is the tool_call record's own start offset (an upper bound of
    # its parent message), a message hit's is the message record's
    assert results[1]["cursor"] == results[2]["cursor"] != results[0]["cursor"]
    assert results[1]["size_hint"] == int(results[1]["cursor"][2:])
    offsets = {}
    pos = 0
    for line in (tmp_path / "m.jsonl").read_bytes().split(b"\n")[:-1]:
        offsets[json.loads(line)["message_id"]] = pos
        pos += len(line) + 1
    assert results[0]["cursor"] == f"b:{offsets['u2']}"
    assert results[1]["cursor"] == f"b:{offsets['tc2']}"  # the newest tool_call record


def test_tool_hits_survive_a_page_cut_between_tool_call_and_parent(tmp_path):
    reader = _tool_history(tmp_path / "m.jsonl", filler=7000)  # > 1 MiB between parent and tools
