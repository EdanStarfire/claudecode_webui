    records = [json.loads(line) for line in src.read_text(encoding="utf-8").split("\n") if line.strip()]
    tiled = _tile(records, EXPECTED["scale_records"])
    assert len(tiled) >= EXPECTED["scale_records"]
    reader = _write(tmp_path / "messages.jsonl", tiled)
    for query in EXPECTED["queries"]:
        results, _ = search_all(reader, query, SearchCaps(max_results=50, max_scan_bytes=10**12, max_wall_s=600))
        assert digest(chronological(results)) == EXPECTED["scale"][query], query


