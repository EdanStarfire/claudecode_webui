def test_prefilter_scan_equals_naive_count_across_block_boundaries(tmp_path):
    """Lines that straddle the 1 MiB read blocks, giant lines and several hits per line produce
    the same results as a naive per-record count."""
    import random

    rng = random.Random(5)
    records = []
    for i in range(300):
        pad = "z" * rng.choice([0, 100, 5_000, 400_000, 1_300_000]) if rng.random() < 0.12 else ""
        text = f"{pad} needle{i} {'needle' if i % 7 == 0 else ''}"
        records.append({"type": rng.choice(["user", "assistant"]), "message_id": f"m{i}", "content": text})
    reader = _write(tmp_path / "m.jsonl", records)
    fast, _ = search_all(reader, "needle")
    # compare against a pure-python findMatches over the records
    want = []
    for rec in reversed(records):
        lower = rec["content"].lower()
        idx, count = lower.find("needle"), 0
        while idx != -1:
            count += 1
            idx = lower.find("needle", idx + 1)
        want += [rec["message_id"]] * count
    assert [r["message_id"] for r in fast] == want


