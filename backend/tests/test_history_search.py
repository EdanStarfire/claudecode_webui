    assert len(results) == 2000
    assert len(pages) > 1 and all(p.stopped_by == "bytes" for p in pages[:-1])
    # one block of overshoot at most (1 MiB blocks; the file here is small -> a single block)
    assert all(p.scanned_bytes <= 64 * 1024 + 1024 * 1024 + 8 for p in pages)


