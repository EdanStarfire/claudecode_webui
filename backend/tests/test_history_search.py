def _write(path: Path, records: list[dict]) -> FileMessageHistoryReader:
    with open(path, "w", encoding="utf-8") as f:
        for r in records:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    return FileMessageHistoryReader(path, strict_legacy=False)


def search_all(reader, query, caps=BIG, *, max_pages=100000):
    """Page to exhaustion; returns (results newest-first, pages)."""
    results, cursor, pages = [], None, []
    for _ in range(max_pages):
        page = reader.search(query, cursor, caps)
        pages.append(page)
        results += page.results
        if page.exhausted:
            return results, pages
        assert page.next_cursor and page.next_cursor != cursor
        cursor = page.next_cursor
    raise AssertionError("search did not terminate")


def chronological(results: list[dict]) -> list[list]:
    """Server newest-first pages -> findMatches' chronological descriptor lists (groups are
    atomic per owning message, internal order preserved)."""
    groups: list[list[dict]] = []
    for r in results:
        if groups and groups[-1][0]["message_id"] == r["message_id"]:
            groups[-1].append(r)
        else:
            groups.append([r])
    return [
        [r["message_id"], r["tool_id"], r["field"], r["match_start"], r["match_length"],
         r["snippet"], r["occurrence_index"]]
        for group in reversed(groups) for r in group
    ]


def digest(descriptors: list[list]) -> dict:
    sha = hashlib.sha1()
    for d in descriptors:
        sha.update((json.dumps(d, ensure_ascii=False, separators=(",", ":")) + "\n").encode())
    return {"count": len(descriptors), "sha1": sha.hexdigest()}


