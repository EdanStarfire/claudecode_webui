def test_search_cursor_roundtrip_and_bounds():
    pending = {"t1": [{"field": "tool_input", "match_start": 3, "match_length": 2, "snippet": "é",
                       "offset": 7}]}
    cursor = encode_search_cursor("h", 42, pending)
    decoded = decode_search_cursor(cursor)
    assert (decoded.history_id, decoded.offset, decoded.pending) == ("h", 42, pending)
    assert decode_search_cursor(encode_search_cursor("h", 42, {})).pending == {}
    too_many = {f"t{i}": pending["t1"] for i in range(25)}
    assert decode_search_cursor(encode_search_cursor("h", 1, too_many)) is None


