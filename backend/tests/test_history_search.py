def _tile(records: list[dict], total: int) -> list[dict]:
    reps = total // len(records) + 1
    out = []
    for rep in range(reps):
        suffix = f"-scale-rep{rep}"
        for record in records:
            copy = json.loads(json.dumps(record))
            if copy.get("message_id"):
                copy["message_id"] += suffix
            if copy.get("tool_use_id"):
                copy["tool_use_id"] += suffix
            uses = (copy.get("metadata") or {}).get("tool_uses")
            if isinstance(uses, list):
                for use in uses:
                    if isinstance(use, dict) and use.get("id"):
                        use["id"] += suffix
            out.append(copy)
    return out


